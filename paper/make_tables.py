"""Turns results/classified.csv into LaTeX tables for the paper (booktabs, IEEEtran-friendly).

Run from the repo root on the machine that holds the final results:

    python paper/make_tables.py > paper/tables.tex

Unit: distinct checks. Every emulator check received the same class in all five runs (the consistency
report on stderr must list none), so a check's class is well defined; run counts are kept in the classes
table. Rates follow analysis/classify.py: blocked, flaky and no_reference checks are left out of the
scored denominator; "false success" counts false_success_a and false_success_b. Nothing is hard-coded.
"""
import collections
import csv
import sys

CSV = sys.argv[1] if len(sys.argv) > 1 else "results/classified.csv"
ENVS = [("aws-emulator", "AWS Emulator"), ("floci", "Floci"), ("ministack", "MiniStack")]
EXCLUDED = {"blocked", "flaky", "no_reference"}
CLASSES = [("match", "Match"), ("mismatch", "Mismatch"), ("false_success_a", "False succ.\\ (accepts)"),
           ("false_success_b", "False succ.\\ (hollow)"), ("false_failure", "False failure"),
           ("blocked", "Blocked"), ("flaky", "No stable AWS reference")]

rows = [r for r in csv.DictReader(open(CSV)) if r["env"] in dict(ENVS)]
workloads = sorted({r["workload"] for r in rows}, key=lambda w: int(w.lstrip("Ww")))

# class per (env, workload, check); report any check whose class varies across runs
seen = collections.defaultdict(set)
runs = collections.Counter()
for r in rows:
    seen[(r["env"], r["workload"], r["check_id"])].add(r["class"])
    runs[(r["env"], r["class"])] += 1
varies = {k: v for k, v in seen.items() if len(v) > 1}
print(f"% checks with more than one class across runs: {len(varies)}", file=sys.stderr)
for k, v in sorted(varies.items()):
    print(f"%   {k}: {sorted(v)}", file=sys.stderr)
cls = {k: sorted(v)[0] for k, v in seen.items()}


def counts(env, wl=None):
    """matched, scored, blocked, flaky, false successes, planned (distinct checks)"""
    c = collections.Counter(v for (e, w, _), v in cls.items() if e == env and (wl is None or w == wl))
    scored = sum(n for k, n in c.items() if k not in EXCLUDED)
    fs = c["false_success_a"] + c["false_success_b"]
    return c["match"], scored, c["blocked"], c["flaky"], fs, sum(c.values())


def pct(num, den):
    return "--" if den == 0 else f"{100 * num / den:.0f}"


out = []
w = out.append
w("% Generated by paper/make_tables.py from " + CSV + " -- do not edit by hand.")

# Agreement and reachability per workload, in distinct checks
w("\\begin{table}[t]")
w("\\caption{Agreement and reachability per workload, in distinct checks: matched/scored (m/s) "
  "and blocked (b). Scored checks exclude blocked checks and checks without a stable, complete AWS reference.}")
w("\\label{tab:rates}")
w("\\centering\\footnotesize\\setlength{\\tabcolsep}{3.5pt}")
w("\\begin{tabular}{@{}l" + "rr" * len(ENVS) + "@{}}")
w("\\toprule")
w(" & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{name}}}" for _, name in ENVS) + " \\\\")
w(" ".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(ENVS))))
w("Workload & " + " & ".join("m/s & b" for _ in ENVS) + " \\\\")
w("\\midrule")
for wl in workloads:
    cells = []
    for env, _ in ENVS:
        m, s, b, _, _, _ = counts(env, wl)
        cells += [f"{m}/{s}", str(b)]
    w(f"{wl} & " + " & ".join(cells) + " \\\\")
w("\\midrule")
cells = []
for env, _ in ENVS:
    m, s, b, _, _, _ = counts(env)
    cells += [f"{m}/{s}", str(b)]
w("All & " + " & ".join(cells) + " \\\\")
w("\\midrule")
METRICS = [("Agreement (\\%)", lambda m, s, b, f, fs, p: pct(m, s)),
           ("Strict (\\%)", lambda m, s, b, f, fs, p: pct(m, p - f)),
           ("False succ.\\ (\\%)", lambda m, s, b, f, fs, p: pct(fs, s))]
for label, fn in METRICS:
    w(label + " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{fn(*counts(env))}}}" for env, _ in ENVS)
      + " \\\\")
w("\\bottomrule")
w("\\end{tabular}")
w("\\\\[2pt]\\parbox{\\columnwidth}{\\scriptsize Strict: matched checks over all checks with a stable "
  "AWS reference, counting blocked checks as not matched.}")
w("\\end{table}")
w("")

# Distinct checks per outcome class (runs in parentheses)
w("\\begin{table}[t]")
w("\\caption{Distinct checks by outcome across all workloads. Each workload ran five times; "
  "the number of planned check instances (checks $\\times$ five runs) is given in parentheses.}")
w("\\label{tab:classes}")
w("\\centering\\footnotesize\\setlength{\\tabcolsep}{4pt}")
w("\\begin{tabular}{l" + "r" * len(ENVS) + "}")
w("\\toprule")
w("Outcome & " + " & ".join(name for _, name in ENVS) + " \\\\")
w("\\midrule")
for c, label in CLASSES:
    cells = []
    for env, _ in ENVS:
        distinct = sum(1 for (e, _, _), v in cls.items() if e == env and v == c)
        cells.append(f"{distinct} ({runs[(env, c)]})")
    w(f"{label} & " + " & ".join(cells) + " \\\\")
w("\\bottomrule")
w("\\end{tabular}")
w("\\end{table}")

print("\n".join(out))
